-- Tasks from the Priority Matrix app, one row per task, per user.
-- Completed tasks are kept (status = 'done'); deleting a task in the app
-- only sets deleted_at, so past days can always be looked up.

create table public.tasks (
  id            uuid primary key,                       -- generated by the app
  user_id       uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title         text not null check (char_length(title) between 1 and 1000),
  quadrant      text not null check (quadrant in ('do', 'schedule', 'delegate', 'eliminate')),
  status        text not null default 'open' check (status in ('open', 'done')),
  task_date     date not null,                          -- the day the task is planned for
  subtasks      jsonb not null default '[]'::jsonb check (jsonb_typeof(subtasks) = 'array'),
  position      integer not null default 0,             -- order within the app
  created_at    timestamptz not null default now(),
  completed_at  timestamptz,
  updated_at    timestamptz not null default now(),
  deleted_at    timestamptz,                            -- set when deleted in the app; row is kept
  constraint open_tasks_have_no_completed_at check (status = 'done' or completed_at is null)
);

create index tasks_user_id_task_date_idx on public.tasks (user_id, task_date);

comment on table public.tasks is
  'Tasks from the Priority Matrix app. Quadrants: do = urgent and important, schedule = important not urgent, delegate = urgent not important, eliminate = neither. Ignore rows where deleted_at is not null.';
comment on column public.tasks.task_date is 'The day the task is planned for (local date). Unfinished tasks are carried over to later days.';
comment on column public.tasks.position is 'Display order in the app; lower comes first.';

-- Keep updated_at current on every change.
create function public.set_updated_at() returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger tasks_set_updated_at
  before update on public.tasks
  for each row execute function public.set_updated_at();

-- Row Level Security: a signed-in user can only see and change their own rows.
alter table public.tasks enable row level security;

create policy "Users can read their own tasks"
  on public.tasks for select to authenticated
  using ((select auth.uid()) = user_id);

create policy "Users can add their own tasks"
  on public.tasks for insert to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users can update their own tasks"
  on public.tasks for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "Users can delete their own tasks"
  on public.tasks for delete to authenticated
  using ((select auth.uid()) = user_id);

-- Signed-out visitors get nothing; signed-in users go through the policies above.
revoke all on public.tasks from anon;
grant select, insert, update, delete on public.tasks to authenticated;
revoke execute on function public.set_updated_at() from public, anon, authenticated;
